-- Items table
CREATE TABLE items (
    item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR2(100),
    item_type VARCHAR2(100),
    company_id NUMBER,
    purchase_price NUMBER(7, 2),
    sale_price NUMBER(7, 2),
    quantity NUMBER
);

-- customer table
CREATE TABLE customers (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_first_name VARCHAR2(100),
    customer_last_name VARCHAR2(100),
    customer_email VARCHAR2(200),
    customer_point_balance NUMBER
);

-- supplier table
CREATE TABLE suppliers (
    company_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR2(200),
    company_website VARCHAR2(200),
    company_location VARCHAR2(200)
);

-- employee table
CREATE TABLE employees (
    employee_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_first_name VARCHAR2(100),
    employee_last_name VARCHAR2(100),
    employee_email VARCHAR2(200),
    hire_date DATE,
    employee_title VARCHAR2(100)
);

-- sales table
CREATE TABLE sales (
    sale_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id NUMBER,
    constraint fk_customers
    FOREIGN KEY (customer_id)
    REFERENCES customers(customer_id),
    employee_id NUMBER,
    constraint fk_employees
    FOREIGN KEY (employee_id)
    REFERENCES employees(employee_id),
    item_id NUMBER,
    constraint fk_items
    FOREIGN KEY (item_id)
    REFERENCES items(item_id),
    sale_total NUMBER(7, 2),
    sale_date DATE,
    points_gained NUMBER
);

